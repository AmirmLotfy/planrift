/**
 * Standalone, printable HTML receipt. Every interpolated value is HTML-escaped; the document
 * has no scripts and no external resources, so it is safe to open from disk.
 */

import { STATUS_LABEL } from '../analysis/explain';
import { formatDeg, formatMeasure } from '../format';
import type { RevisionReceipt } from '../revision/receipt';
import { shortFingerprint } from './canonical';

export function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const e = escapeHtml;

export function receiptHtml(receipt: RevisionReceipt): string {
  const decision = receipt.decision;
  const rows = receipt.analysis.pairs
    .filter((p) => p.status !== 'PASS' || receipt.changes.some((c) => c.elementId === p.doorId))
    .map(
      (p) => `<tr><td class="m">${e(p.doorId)} × ${e(p.furnitureId)}</td><td>${e(STATUS_LABEL[p.status])}</td><td class="m">${
        p.separationMm === null ? '—' : e(formatMeasure(p.separationMm))
      }</td><td class="m">${p.firstStrikeDeg === null ? '—' : e(formatDeg(p.firstStrikeDeg))}</td></tr>`,
    )
    .join('');
  const impacts = receipt.impacts.length
    ? receipt.impacts
        .map(
          (i) =>
            `<li><strong class="m">${e(i.documentId)}</strong> ${e(i.title)} (issued rev ${e(i.revision)}) — <span class="copper">Review required</span><ul>${i.reasons
              .map((r) => `<li>${e(r.description)} · <em>${e(r.linkNote)}</em></li>`)
              .join('')}</ul></li>`,
        )
        .join('')
    : '<li>No linked documents affected.</li>';
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">
<title>${e(receipt.id)} · PLANRIFT revision receipt</title>
<style>
  body{font:14px/1.5 -apple-system,'Segoe UI',Helvetica,Arial,sans-serif;color:#202b31;background:#f4f2ec;margin:0;padding:32px}
  main{max-width:820px;margin:0 auto;background:#fbfaf6;border:1px solid #ddd9cf;border-radius:10px;padding:32px 36px}
  h1{font-size:22px;margin:0 0 4px}h2{font-size:15px;margin:28px 0 8px;border-bottom:1px solid #ddd9cf;padding-bottom:6px}
  .m{font-family:ui-monospace,Menlo,monospace}.muted{color:#5f6866}.copper{color:#845a33;font-weight:600}
  .outcome{display:inline-block;padding:3px 12px;border-radius:999px;font-weight:700}
  .accepted{background:#e0ece8;color:#377467}.rejected{background:#f6e3df;color:#a3473a}
  table{border-collapse:collapse;width:100%}td,th{text-align:left;padding:6px 8px;border-bottom:1px solid #ece8de;vertical-align:top}
  dl{display:grid;grid-template-columns:180px 1fr;gap:6px 16px;margin:0}dt{color:#5f6866}
  footer{margin-top:28px;font-size:12px;color:#5f6866}
  @media print{body{background:#fff;padding:0}main{border:none}}
</style>
</head>
<body>
<main>
  <p class="muted m">PLANRIFT REVISION RECEIPT · ${e(receipt.id)}</p>
  <h1>${e(receipt.project.name)}</h1>
  <p>${e(receipt.scenario.name)} (Revision ${e(receipt.scenario.label)}) — <span class="outcome ${decision.outcome === 'accepted' ? 'accepted' : 'rejected'}">${
    decision.outcome === 'accepted' ? 'Accepted' : 'Rejected'
  }</span></p>
  <h2>Decision</h2>
  <dl>
    <dt>Reviewer</dt><dd>${e(decision.reviewer || 'Not recorded')}</dd>
    <dt>Decided at</dt><dd class="m">${e(decision.decidedAt)}</dd>
    <dt>Note</dt><dd>${e(decision.note || '—')}</dd>
    <dt>Documents acknowledged</dt><dd>${decision.acknowledgedDocuments ? 'Yes — the team will revise and re-issue them' : 'No'}</dd>
  </dl>
  <h2>Provenance</h2>
  <dl>
    <dt>Source revision</dt><dd class="m">${e(receipt.source.revisionId)} · ${e(shortFingerprint(receipt.source.fingerprint))}</dd>
    <dt>Result</dt><dd class="m">${e(receipt.result.revisionId ?? 'not committed')} · ${e(shortFingerprint(receipt.result.fingerprint))}</dd>
    <dt>Engine</dt><dd class="m">${e(receipt.analysis.engineVersion)} · tolerance ±${e(receipt.analysis.settings.contactToleranceMm)} mm · advisory ${e(receipt.analysis.settings.nearClearanceMm)} mm</dd>
  </dl>
  <h2>Changes</h2>
  <ul>${receipt.changes.map((c) => `<li>${e(c.description)}</li>`).join('') || '<li>No changes.</li>'}</ul>
  <h2>Computed results · overall ${e(STATUS_LABEL[receipt.analysis.status])}</h2>
  <table><thead><tr><th>Pair</th><th>Status</th><th>Separation</th><th>First strike</th></tr></thead><tbody>${rows}</tbody></table>
  <h2>Documents requiring review</h2>
  <ul>${impacts}</ul>
  <h2>Limitations</h2>
  <ul>${receipt.limitations.map((l) => `<li>${e(l)}</li>`).join('')}</ul>
  <footer>This receipt is a review record generated by PLANRIFT. It is not a construction certificate, a compliance statement or an approval to build.</footer>
</main>
</body>
</html>`;
}
